#!/usr/bin/env node
// Exports contract ABIs, enum definitions and deployment addresses from Foundry's `out/` and
// `deployments/` into packages/shared, as typed `as const` TypeScript (ready for viem).
// Run `forge build` first (the `export-abi` package script does).
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sharedSrc = join(root, "..", "shared", "src");
const abiDir = join(sharedSrc, "abi");
const LOCAL_CHAINS = new Set([31337]);

const CONTRACTS = [
  { name: "PersonhoodRegistry", file: "personhood-registry", id: "personhoodRegistry" },
  { name: "MissionEscrow", file: "mission-escrow", id: "missionEscrow" },
];

const HEADER =
  "// Generated by packages/contracts/scripts/export-abi.mjs. Do not edit by hand.\n" +
  "// Regenerate with: pnpm -F @seenit/contracts export-abi\n\n";

function collectEnums(node, out = {}) {
  if (Array.isArray(node)) node.forEach((n) => collectEnums(n, out));
  else if (node && typeof node === "object") {
    if (node.nodeType === "EnumDefinition") out[node.name] = node.members.map((m) => m.name);
    Object.values(node).forEach((v) => collectEnums(v, out));
  }
  return out;
}

mkdirSync(abiDir, { recursive: true });
const written = [];

for (const c of CONTRACTS) {
  const artifactPath = join(root, "out", `${c.name}.sol`, `${c.name}.json`);
  if (!existsSync(artifactPath)) throw new Error(`Missing ${artifactPath}. Run forge build first.`);
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  if (!artifact.ast) throw new Error("Artifact has no AST. Is `ast = true` set in foundry.toml?");

  const enums = collectEnums(artifact.ast);
  const out = join(abiDir, `${c.file}.ts`);
  writeFileSync(
    out,
    `${HEADER}export const ${c.id}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n` +
      `/** Solidity enum members in declaration order (index = on-chain value). */\n` +
      `export const ${c.id}Enums = ${JSON.stringify(enums, null, 2)} as const;\n`,
  );
  written.push(out);
}

const indexPath = join(abiDir, "index.ts");
writeFileSync(
  indexPath,
  HEADER + CONTRACTS.map((c) => `export * from "./${c.file}.js";\n`).join(""),
);
written.push(indexPath);

// Deployments (non-local chains only).
const deploymentsDir = join(root, "deployments");
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir)
    .filter((f) => f.endsWith(".json"))
    .sort()) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    if (LOCAL_CHAINS.has(d.chainId)) continue;
    deployments[d.chainId] = {
      personhoodRegistry: d.personhoodRegistry,
      missionEscrow: d.missionEscrow,
      rewardToken: d.rewardToken,
      blockNumber: d.blockNumber,
    };
  }
}
const deploymentsPath = join(sharedSrc, "deployments.ts");
writeFileSync(
  deploymentsPath,
  `${HEADER}export interface SeenitDeployment {\n  personhoodRegistry: \`0x\${string}\`;\n  missionEscrow: \`0x\${string}\`;\n  rewardToken: \`0x\${string}\`;\n  blockNumber: number;\n}\n\n` +
    `/** Deployed contract addresses by chain ID (filled by script/Deploy.s.sol). */\n` +
    `export const deployments: Partial<Record<number, SeenitDeployment>> = ${JSON.stringify(deployments, null, 2)};\n`,
);
written.push(deploymentsPath);

// Format with the workspace Prettier so `pnpm format:check` stays green.
const prettier = join(root, "..", "..", "node_modules", ".bin", "prettier");
if (existsSync(prettier))
  execFileSync(prettier, ["--write", "--log-level", "warn", ...written], { stdio: "inherit" });

console.log(
  `Exported ${CONTRACTS.length} ABIs and ${Object.keys(deployments).length} deployment(s) to packages/shared.`,
);
